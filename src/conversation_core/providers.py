from pathlib import Path
from typing import Protocol
from .domain import *

class TranscriptionProvider(Protocol):
    async def transcribe(self, audio_path: Path, *, language: str | None = None) -> TranscriptionResult: ...
class ConversationProcessingProvider(Protocol):
    async def process(self, *, transcript: TranscriptInput, mode: ProcessingMode, participants: list[ParticipantInput], segments: list[SegmentInput]) -> ProcessingResult: ...
class DiarizationProvider(Protocol):
    async def diarize(self, audio_path: Path, transcript: TranscriptionResult) -> dict: ...
class SpeakerMappingProvider(Protocol):
    async def map_speakers(self, conversation: object, diarization: dict, source_metadata: dict) -> dict: ...
class RecorderCallProvider(Protocol):
    async def list_available_groups(self, recorder_id: str) -> list[dict]: ...
    async def detect_active_call(self, recorder_id: str, chat_id: str) -> dict | None: ...
    async def join_call(self, recorder_id: str, chat_id: str) -> dict: ...
    async def leave_call(self, recorder_id: str, chat_id: str) -> dict: ...
    async def start_capture(self, recorder_id: str, chat_id: str) -> dict: ...
    async def stop_capture(self, recorder_id: str, chat_id: str) -> dict: ...

class NoopDiarizationProvider:
    async def diarize(self, audio_path: Path, transcript: TranscriptionResult) -> dict: return {"segments": []}
class NoopSpeakerMappingProvider:
    async def map_speakers(self, conversation: object, diarization: dict, source_metadata: dict) -> dict: return {}
